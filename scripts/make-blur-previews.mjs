// Tiny blurred previews for every local content image, shown while the real one loads.
// Writes src/lib/placeholders.ts. Usage: node scripts/make-blur-previews.mjs
import sharp from "sharp";
import { readdir, writeFile } from "node:fs/promises";
import { join, relative } from "node:path";

const root = "public";
async function* walk(dir) {
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) yield* walk(p);
    else if (/\.(webp|jpe?g|png|avif)$/i.test(e.name)) yield p;
  }
}
const rows = [];
for await (const file of walk(join(root, "content"))) {
  const buf = await sharp(file).resize(12, 12, { fit: "inside" }).webp({ quality: 40 }).toBuffer();
  rows.push(`  "/${relative(root, file)}": "data:image/webp;base64,${buf.toString("base64")}",`);
}
rows.sort();
await writeFile(
  "src/lib/placeholders.ts",
  `// Generated by scripts/make-blur-previews.mjs: 12 px previews of the images in public/content.\n` +
    `const PREVIEWS: Record<string, string> = {\n${rows.join("\n")}\n};\n\n` +
    `/** next/image props for a blurred preview while \`src\` loads (none for remote images). */\n` +
    `export function blurOf(src: string) {\n` +
    `  const blurDataURL = PREVIEWS[src];\n` +
    `  return blurDataURL ? ({ placeholder: "blur", blurDataURL } as const) : {};\n}\n`,
);
console.log(`${rows.length} previews → src/lib/placeholders.ts`);
