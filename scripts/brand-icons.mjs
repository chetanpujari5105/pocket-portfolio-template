// Copies the official brand logos we link to into src/components/os/brand-icons.ts, so the app
// never bundles the whole icon packages. Sources: simple-icons (CC0) and, for LinkedIn (which
// simple-icons no longer carries at LinkedIn's request), Font Awesome Free brands (CC BY 4.0).
// Usage: node scripts/brand-icons.mjs
import { writeFile } from "node:fs/promises";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const si = require("simple-icons");
const fa = require("@fortawesome/free-brands-svg-icons");

// Tile per brand, in the brand's own colours: white on its colour, or its colour on white.
// `size` is the mark's share of the tile (optical sizing: dense marks smaller, open marks larger).
const TILES = {
  linkedin: { bg: "#0A66C2", fg: "#fff", size: 0.62 },
  x: { bg: "#000", fg: "#fff", size: 0.56 },
  youtube: { bg: "#fff", fg: "#FF0000", size: 0.62 },
  instagram: {
    bg: "radial-gradient(circle at 30% 107%, #fdf497 0%, #fdf497 5%, #fd5949 45%, #d6249f 60%, #285aeb 90%)",
    fg: "#fff",
    size: 0.56,
  },
  substack: { bg: "#FF6719", fg: "#fff", size: 0.46 },
  udemy: { bg: "#A435F0", fg: "#fff", size: 0.5 },
  github: { bg: "#181717", fg: "#fff", size: 0.58 },
  skillshare: { bg: "#00FF84", fg: "#000", size: 0.52 },
  coursera: { bg: "#0056D2", fg: "#fff", size: 0.56 },
  packt: { bg: "#F37143", fg: "#fff", size: 0.58 },
  oreilly: { bg: "#D3002D", fg: "#fff", size: 0.56 },
};

// Social marks ship with the home screen; platform marks only with the Platforms app.
const FILES = {
  "brand-marks.ts": ["linkedin", "x", "youtube", "instagram", "substack", "udemy", "github"],
  "brand-marks-platforms.ts": ["skillshare", "coursera", "packt", "oreilly"],
};

function mark(slug) {
  if (slug === "linkedin") {
    const [w, h, , , path] = fa.faLinkedinIn.icon;
    return { title: "LinkedIn", hex: "#0A66C2", viewBox: `0 0 ${w} ${h}`, path };
  }
  const icon = si[`si${slug[0].toUpperCase()}${slug.slice(1)}`];
  if (!icon) throw new Error(`simple-icons has no ${slug}`);
  return { title: icon.title, hex: `#${icon.hex}`, viewBox: "0 0 24 24", path: icon.path };
}

for (const [file, slugs] of Object.entries(FILES)) {
  const body = slugs
    .map((slug) => `export const ${slug}: BrandMark = ${JSON.stringify({ id: slug, ...mark(slug), tile: TILES[slug] }, null, 2)};`)
    .join("\n\n");
  const out = `// Generated by scripts/brand-icons.mjs. Don't edit by hand.
// Official brand marks: simple-icons (CC0 1.0) and Font Awesome Free brands (CC BY 4.0, LinkedIn).
// Used only to link to the site owner's own profiles, in each brand's own colours.

import type { BrandMark } from "./BrandIcon";

${body}
`;
  await writeFile(new URL(`../src/components/os/${file}`, import.meta.url), out);
}
console.log("Wrote brand marks");
